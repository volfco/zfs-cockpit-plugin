// Isolated mocked UI check. Requires Node >=22 and Firefox BiDi:
// firefox --headless --no-remote --profile /tmp/zfs-ui-profile --remote-debugging-port 9222
// node test/ui-check.mjs (optional ZFS_BIDI_URL, default ws://127.0.0.1:9222/session)
// All zfs/zpool calls are mocked (test/ui/fixtures.ts); no host storage is touched.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
