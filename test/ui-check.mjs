    assert(await has('.pf-v6-c-description-list__group', 'resilvered 4.50K'), 'scan line');
    assert(await has('.zfs-vdev-section', 'logs', true), 'logs section');
    assert(await has('.zfs-vdev-section', 'cache', true), 'cache section');
    assert(await has('.zfs-vdev-section', 'spares', true), 'spares section');
    assert(await has('.pf-v6-c-table__td', 'raidz1-0'), 'raidz1-0 row');
    assert(await has('.pf-v6-c-table__td', 'mirror-1'), 'log mirror row');
    assert.equal(await count('table[aria-label="Virtual devices of pool scratch"] tbody'), 14, 'vdev tree rows');
