let pass = 0;
let fail = 0;
for (const [name, call, argv, throws] of cases) {
    let threw = false;
    try {
        await call();
    } catch {
        threw = true;
    }
    const got = takeCalls();
    if (throws) {
        if (threw) pass++;
        else {
            fail++;
            console.error(`FAIL ${name}: expected the wrapper to reject the option combination`);
        }
        continue;
    }
    if (threw) {
        fail++;
        console.error(`FAIL ${name}: wrapper threw unexpectedly`);
        continue;
    }
    // Every wrapper above runs exactly one cockpit.spawn; argv is what it gets.
    if (got.length === 1 && JSON.stringify(got[0]) === JSON.stringify(argv)) {
        pass++;
    } else {
        fail++;
        console.error(`FAIL ${name}\n  want ${JSON.stringify(argv)}\n  got  ${JSON.stringify(got)}`);
    }
}
console.log(`argv-check: ${pass}/${cases.length} wrapper argv checks passed`);
if (fail > 0) process.exit(1);
